'use strict';

// Mission Control service worker (scope /). CONTRACTS §12.29 (MC2).
//
// - Shell: `install` precaches every shell file into `mc-shell-<VERSION>` in one piece (cache.addAll; if any
//   file fails, the old worker keeps serving). Shell paths are answered from that cache, so the page is always
//   one version and a 502 from `tailscale serve` never replaces it. `activate` drops old versions.
// - `/api/cards` and `/api/briefing`: always the network. Each 200 JSON object is saved with the time it
//   arrived (`savedAt`, epoch ms) in `mc-data-v1`, for the page to show when the server can't be reached.
//   Errors, 304s and non-objects never replace it.
// - Push: payload {title, body, tag, card, url} (README). Shows the notification; the tap opens the app at
//   that card (`/#card-<id>`), or focuses an open window and asks it to show the card.
// - Everything else goes to the network untouched.

// <shell> Generated by scripts/stamp-sw.mjs from the files in public/. Run `npm run stamp` after changing any.
const VERSION = '26cbf5b60dd207a7';
const SHELL = [
  '/css/app.css',
  '/icons/apple-touch-icon.png',
  '/icons/badge-96.png',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon.svg',
  '/icons/maskable-512.png',
  '/',
  '/js/api.js',
  '/js/app.js',
  '/js/dom.js',
  '/js/main.js',
  '/js/model.js',
  '/js/push.js',
  '/js/view.js',
  '/manifest.webmanifest',
];
// </shell>

const SHELL_PREFIX = 'mc-shell-';
const SHELL_CACHE = `${SHELL_PREFIX}${VERSION}`;
const DATA_CACHE = 'mc-data-v1';
const META_CACHE = 'mc-meta'; // the device label push.js saved
const SNAPSHOTS = { '/api/cards': '/__snapshot/cards', '/api/briefing': '/__snapshot/briefing' };
const SHELL_PATHS = new Set(SHELL);
const CARDS = ['briefing', 'ai', 'ai_control', 'money', 'school', 'home', 'servers', 'alerts'];
const DEFAULT_TITLE = 'Mission Control';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL.map((p) => new Request(p, { cache: 'reload', credentials: 'same-origin' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith(SHELL_PREFIX) && n !== SHELL_CACHE).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

async function fromShell(request, key) {
  const cache = await caches.open(SHELL_CACHE);
  const hit = await cache.match(key);
  if (hit) return hit;
  try {
    const res = await fetch(request);
    if (res.ok) await cache.put(key, res.clone());
    return res;
  } catch {
    return Response.error();
  }
}

function isPlainObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

async function dataFetch(request, key) {
  const res = await fetch(request); // a network error reaches the page, which then reads the snapshot
  if (res.status === 200) {
    res
      .clone()
      .json()
      .then(async (data) => {
        if (!isPlainObject(data)) return;
        const cache = await caches.open(DATA_CACHE);
        await cache.put(key, new Response(JSON.stringify({ savedAt: Date.now(), data }), { headers: { 'Content-Type': 'application/json' } }));
      })
      .catch(() => {});
  }
  return res;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (Object.hasOwn(SNAPSHOTS, url.pathname)) {
    event.respondWith(dataFetch(request, SNAPSHOTS[url.pathname]));
    return;
  }
  if (request.mode === 'navigate') {
    if (url.pathname === '/' || url.pathname === '/index.html') event.respondWith(fromShell(request, '/'));
    return;
  }
  if (url.pathname !== '/' && SHELL_PATHS.has(url.pathname)) event.respondWith(fromShell(request, url.pathname));
});

// --- push ----------------------------------------------------------------------------------------

function parsePayload(data) {
  if (!data) return {};
  try {
    const v = data.json();
    return isPlainObject(v) ? v : {};
  } catch {
    try {
      return { body: data.text() };
    } catch {
      return {};
    }
  }
}

const clip = (s, n) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

/** Where a tap goes: the card's anchor, else a same-origin `url`, else the app root. Never another origin. */
function target(payload) {
  const root = new URL('/', self.location.origin);
  if (typeof payload.card === 'string' && CARDS.includes(payload.card)) {
    root.hash = `card-${payload.card}`;
    return { url: root.href, card: payload.card };
  }
  if (typeof payload.url === 'string' && payload.url) {
    try {
      const u = new URL(payload.url, self.location.origin);
      if (u.origin === self.location.origin) {
        const m = /^#card-([a-z_]+)$/.exec(u.hash);
        return { url: u.href, card: m && CARDS.includes(m[1]) ? m[1] : null };
      }
    } catch {
      // fall through to the root
    }
  }
  return { url: root.href, card: null };
}

self.addEventListener('push', (event) => {
  const p = parsePayload(event.data);
  const title = typeof p.title === 'string' && p.title.trim() ? clip(p.title.trim(), 120) : DEFAULT_TITLE;
  const options = {
    body: typeof p.body === 'string' ? clip(p.body, 400) : '',
    icon: '/icons/icon-192.png',
    badge: '/icons/badge-96.png',
    data: target(p),
  };
  if (typeof p.tag === 'string' && p.tag) {
    options.tag = clip(p.tag, 64); // replaces an earlier notification with the same tag
    options.renotify = true; // ...and still alerts
  }
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const data = event.notification.data;
  const t = target(isPlainObject(data) ? data : {});
  event.waitUntil(
    (async () => {
      const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      for (const client of windows) {
        let here;
        try {
          here = new URL(client.url);
        } catch {
          continue;
        }
        if (here.origin !== self.location.origin) continue;
        // The app is open: ask it to show the card (it keeps any typed text), then bring it forward.
        if (t.card && typeof client.postMessage === 'function') client.postMessage({ type: 'open-card', card: t.card });
        return client.focus();
      }
      return self.clients.openWindow(t.url);
    })(),
  );
});

// --- the browser replaced the subscription: register the new one so notifications keep arriving -----

function b64urlToBytes(value) {
  const b64 = value.replace(/-/g, '+').replace(/_/g, '/').padEnd(Math.ceil(value.length / 4) * 4, '=');
  return Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
}

function post(path, body) {
  return fetch(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-Mission-Control': '1' },
    body: JSON.stringify(body),
    credentials: 'same-origin',
  });
}

self.addEventListener('pushsubscriptionchange', (event) => {
  event.waitUntil(
    (async () => {
      let sub = event.newSubscription;
      if (!sub) {
        const res = await fetch('/api/cards', { cache: 'no-store', credentials: 'same-origin' });
        if (!res.ok) return;
        const key = (await res.json())?.config?.vapid_public_key;
        if (typeof key !== 'string' || !key) return;
        sub = await self.registration.pushManager.subscribe({ userVisibleOnly: true, applicationServerKey: b64urlToBytes(key) });
      }
      let label = 'Device';
      try {
        const hit = await (await caches.open(META_CACHE)).match('/__label');
        if (hit) label = (await hit.text()).slice(0, 64) || label;
      } catch {
        // keep the default
      }
      await post('/api/push/subscribe', { subscription: sub.toJSON(), label });
      if (event.oldSubscription && event.oldSubscription.endpoint !== sub.endpoint) await post('/api/push/unsubscribe', { endpoint: event.oldSubscription.endpoint });
    })().catch(() => {}),
  );
});
