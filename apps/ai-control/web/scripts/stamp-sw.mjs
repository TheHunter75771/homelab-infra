#!/usr/bin/env node
// Writes the shell file list and a content hash into public/sw.js (between the <shell> markers), so any
// change to a shell file installs a new worker. `--check` exits 1 if sw.js is stale (the tests call it).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const PUBLIC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');

function list(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.name.startsWith('.')) return [];
    return e.isDirectory() ? list(p, base) : [path.relative(base, p).split(path.sep).join('/')];
  });
}

/** Every file the page may load: all of public/ except the worker itself and license texts. */
export function shellFiles(dir = PUBLIC) {
  return list(dir)
    .filter((f) => f !== 'sw.js' && !/(^|\/)LICENSE[^/]*$/.test(f))
    .sort();
}

export function shellBlock(dir = PUBLIC) {
  const files = shellFiles(dir);
  const hash = crypto.createHash('sha256');
  for (const f of files) hash.update(`${f}\0`).update(fs.readFileSync(path.join(dir, f))).update('\0');
  const urls = files.map((f) => (f === 'index.html' ? '/' : `/${f}`));
  return [
    '// <shell> Generated by scripts/stamp-sw.mjs from the files in public/. Run `npm run stamp` after changing any.',
    `const VERSION = '${hash.digest('hex').slice(0, 16)}';`,
    'const SHELL = [',
    ...urls.map((u) => `  '${u}',`),
    '];',
    '// </shell>',
  ].join('\n');
}

const BLOCK = /\/\/ <shell>[\s\S]*?\/\/ <\/shell>/;

export function isStale(dir = PUBLIC) {
  const sw = fs.readFileSync(path.join(dir, 'sw.js'), 'utf8');
  return sw.replace(BLOCK, shellBlock(dir)) !== sw;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const swPath = path.join(PUBLIC, 'sw.js');
  const sw = fs.readFileSync(swPath, 'utf8');
  if (!BLOCK.test(sw)) throw new Error('sw.js has no <shell> block');
  const next = sw.replace(BLOCK, shellBlock());
  if (process.argv.includes('--check')) {
    if (next !== sw) {
      console.error('public/sw.js is out of date: run npm run stamp');
      process.exit(1);
    }
    console.log('sw.js is up to date');
  } else {
    fs.writeFileSync(swPath, next);
    console.log(next === sw ? 'sw.js is up to date' : 'stamped sw.js');
  }
}
