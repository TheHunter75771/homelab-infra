'use strict';

// AI Control service worker (scope /). CONTRACTS §12.15.6: caches the shell and the last summary.
//
// - Shell: `install` precaches every shell file into `aictl-shell-<VERSION>` in one piece (cache.addAll;
//   if any file fails, the old worker keeps serving). Shell paths are answered from that cache, so a page is
//   always one version and a 502 from `tailscale serve` can never replace it. `activate` drops old versions.
// - `/api/summary`: always the network. A 200 is saved with the time it arrived (`savedAt`, epoch ms) under
//   `/__snapshot` in `aictl-data-v1`; the page reads it when the server can't be reached and shows its age.
//   A 304 or an error never replaces it.
// - Everything else (the other /api/* calls, /api/events) is left to the network untouched.

// <shell> Generated by scripts/stamp-sw.mjs from the files in public/. Run `npm run stamp` after changing any.
const VERSION = '0b9f19784a09b483';
const SHELL = [
  '/css/app.css',
  '/icons/icon.svg',
  '/',
  '/js/api.js',
  '/js/app.js',
  '/js/dom.js',
  '/js/explain.js',
  '/js/format.js',
  '/js/main.js',
  '/js/shell.js',
  '/js/spark.js',
  '/js/state.js',
  '/js/tabs/audit.js',
  '/js/tabs/logs.js',
  '/js/tabs/models.js',
  '/js/tabs/overview.js',
  '/js/tabs/routing.js',
  '/js/ui.js',
  '/manifest.webmanifest',
];
// </shell>

const SHELL_PREFIX = 'aictl-shell-';
const SHELL_CACHE = `${SHELL_PREFIX}${VERSION}`;
const DATA_CACHE = 'aictl-data-v1';
const SNAPSHOT_KEY = '/__snapshot';
const SHELL_PATHS = new Set(SHELL);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL.map((p) => new Request(p, { cache: 'reload', credentials: 'same-origin' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith(SHELL_PREFIX) && n !== SHELL_CACHE).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

async function fromShell(request, key) {
  const cache = await caches.open(SHELL_CACHE);
  const hit = await cache.match(key);
  if (hit) return hit;
  try {
    const res = await fetch(request);
    if (res.ok) await cache.put(key, res.clone());
    return res;
  } catch {
    return Response.error();
  }
}

function isPlainObject(v) {
  return v !== null && typeof v === 'object' && !Array.isArray(v);
}

async function summaryFetch(request) {
  const res = await fetch(request); // a network error reaches the page, which then reads the snapshot
  if (res.status === 200) {
    res
      .clone()
      .json()
      .then(async (summary) => {
        if (!isPlainObject(summary)) return;
        const cache = await caches.open(DATA_CACHE);
        await cache.put(SNAPSHOT_KEY, new Response(JSON.stringify({ savedAt: Date.now(), summary }), { headers: { 'Content-Type': 'application/json' } }));
      })
      .catch(() => {});
  }
  return res;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/api/summary') {
    event.respondWith(summaryFetch(request));
    return;
  }
  if (request.mode === 'navigate') {
    if (url.pathname === '/' || url.pathname === '/index.html') event.respondWith(fromShell(request, '/'));
    return;
  }
  if (url.pathname !== '/' && SHELL_PATHS.has(url.pathname)) event.respondWith(fromShell(request, url.pathname));
});
