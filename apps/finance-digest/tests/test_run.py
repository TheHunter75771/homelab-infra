class SanitiseTest(RunBase):
    def test_hostile_strings_are_inert_in_the_log(self):
        self.hub.state = copy.deepcopy(fakes.STATE_FAILING)
        self.broker.reply = "See [x](https://evil.example) now."  # no numbers; kept but inert
        self.run_digest()
        text = self.read_log()
        body = fm.parse(text)[1]
        for bad in ("](", "![", "://", "\x1b", "\u202e", "<img", "www."):
            self.assertNotIn(bad, body, bad)
        markers = [l for l in body.splitlines() if "finance-digest:" in l and l.startswith("<!--")]
        self.assertEqual(markers, ["<!-- finance-digest:begin 2030-03-20 -->", "<!-- finance-digest:end 2030-03-20 -->"])
        tables, current = [], []
        for line in body.splitlines() + [""]:
            if line.startswith("|"):
                current.append(line.count("|"))
            elif current:
                tables.append(current)
                current = []
        self.assertEqual(len(tables), 6)  # balances, budget, due, overdue, debt, payday
        for counts in tables:
            self.assertEqual(len(set(counts)), 1, counts)  # no forged cells anywhere
        bill_rows = [l for l in body.splitlines() if "2030-03-21" in l and l.startswith("|")]
        self.assertEqual(len(bill_rows), 1)
        self.assertEqual(bill_rows[0].count("|"), 5)  # 4 columns: the name's pipes were neutralised
        # a forged end marker in a name must not confuse a rerun
        self.run_digest()
        self.assertEqual(self.read_log(), text)


class LogSafetyTest(RunBase):
    def test_symlinked_log_file_is_refused(self):
        target = os.path.join(self.tmp, "outside.md")
        put(target, "outside\n")
        os.symlink(target, self.log_path())
        code, _ = self.run_digest()
        self.assertEqual(code, 2)
        self.assertEqual(get(target), "outside\n")
        self.assertTrue(os.path.islink(self.log_path()))

    def test_symlinked_log_dir_is_refused(self):
        os.rmdir(os.path.join(self.lib.root, "50-finance/log"))
        os.makedirs(os.path.join(self.tmp, "elsewhere"))
        os.symlink(os.path.join(self.tmp, "elsewhere"), os.path.join(self.lib.root, "50-finance/log"))
        code, _ = self.run_digest()
        self.assertEqual(code, 2)
        self.assertEqual(os.listdir(os.path.join(self.tmp, "elsewhere")), [])

    def test_damaged_markers_stop_the_write(self):
        self.run_digest()
        broken = self.read_log().replace("<!-- finance-digest:end 2030-03-20 -->\n", "")
        put(self.log_path(), broken)
        code, _ = self.run_digest(dt.date(2030, 3, 21))
        self.assertEqual(code, 2)
        self.assertEqual(self.read_log(), broken)

    def test_library_check_passes(self):
        self.hub.state = copy.deepcopy(fakes.STATE_FAILING)
        self.run_digest(dt.date(2030, 3, 19))
        self.run_digest(D)
        self.run_digest(D)
        self.run_digest(dt.date(2030, 4, 1))
        self.assertEqual(self.lib.check(), [])

    def test_sentinel_required(self):
        sentinel = os.path.join(self.lib.root, SENTINEL_NAME)
        os.unlink(sentinel)
        before = self.tree()
        code, _ = self.run_digest()
        self.assertEqual(code, 2)
        self.assertEqual(self.tree(), before)
        self.assertEqual(self.hub.requests, [])
        self.assertEqual(self.broker.requests, [])
        self.assertIn("is missing", self.logs)
        # a symlink or a folder does not count
        put(os.path.join(self.tmp, "elsewhere-sentinel"), "x")
        os.symlink(os.path.join(self.tmp, "elsewhere-sentinel"), sentinel)
        self.assertEqual(self.run_digest()[0], 2)
        os.unlink(sentinel)
        os.mkdir(sentinel)
        self.assertEqual(self.run_digest()[0], 2)
        self.assertIn("not a regular file", self.logs)
        self.assertFalse(os.path.exists(self.log_path()))
        os.rmdir(sentinel)
        put(sentinel, "mounted\n")
        self.assertEqual(self.run_digest()[0], 0)
        self.assertTrue(os.path.exists(self.log_path()))

    def test_empty_month_file_is_treated_as_new(self):
        put(self.log_path(), "")  # e.g. a name reserved by an interrupted write
        code, _ = self.run_digest()
        self.assertEqual(code, 0)
        meta, body = fm.parse(self.read_log())
        self.assertEqual(fm.validate(meta), [])
        self.assertEqual(meta["title"], "Finance log 2030-03")
        self.assertEqual(body.count("<!-- finance-digest:begin 2030-03-20 -->"), 1)
        self.assertIn("created 2030-03-20", self.logs)
        self.assertEqual(self.lib.check(), [])

    def test_file_changed_between_read_and_rename_is_not_overwritten(self):
        self.run_digest(dt.date(2030, 3, 19))
        real_read = logfile._read

        def read_then_someone_edits(path):
            result = real_read(path)
            with open(path, "a", encoding="utf-8") as fh:  # e.g. Noah saving over Samba
                fh.write("\nedited meanwhile\n")
            return result

        with mock.patch.object(logfile, "_read", read_then_someone_edits):
            code, _ = self.run_digest(D)
        self.assertEqual(code, 2)
        text = self.read_log()
        self.assertIn("edited meanwhile", text)
        self.assertNotIn("<!-- finance-digest:begin 2030-03-20 -->", text)
        self.assertIn("changed while it was being written", self.logs)

    def test_read_never_follows_a_symlink(self):
        target = os.path.join(self.tmp, "outside.md")
        put(target, "outside\n")
        link = os.path.join(self.tmp, "link.md")
        os.symlink(target, link)
        with self.assertRaises(logfile.LogError):
            logfile._read(link)
        self.assertEqual(logfile._read(target)[0], "outside\n")

    def test_no_temp_files_left(self):
        self.run_digest()
        self.run_digest()
        names = os.listdir(os.path.join(self.lib.root, "50-finance/log"))
        self.assertEqual(names, ["2030-03-01_finance-log.md"])

    def test_merge_unit(self):
        e1 = "## 2030-03-01\n\none\n"
        t = logfile.new_file_text(dt.date(2030, 3, 1), e1)
        t2 = logfile.merge(t, dt.date(2030, 3, 2), "## 2030-03-02\n\ntwo\n")
        t3 = logfile.merge(t2, dt.date(2030, 3, 1), "## 2030-03-01\n\nONE\n")
        self.assertIn("ONE", t3)
        self.assertNotIn("\none\n", t3)
        self.assertEqual(t3.split("<!-- finance-digest:begin 2030-03-02 -->")[1], t2.split("<!-- finance-digest:begin 2030-03-02 -->")[1])
        for bad in ("<!-- finance-digest:begin 2030-03-01 -->\nx\n",
                    "<!-- finance-digest:end 2030-03-01 -->\n",
                    "<!-- finance-digest:begin 2030-03-01 -->\n<!-- finance-digest:begin 2030-03-02 -->\n",
                    "<!-- finance-digest:begin 2030-03-01 -->\n<!-- finance-digest:end 2030-03-01 -->\n" * 2,
                    "<!-- finance-digest:begin 2030-3-1 -->\n"):
            with self.assertRaises(logfile.LogError, msg=bad):
                logfile.merge(bad, dt.date(2030, 3, 5), "x")


class NotionTest(RunBase):
    PAGE = "0123456789abcdef0123456789ABCDEF"

    def write_notion(self, data):
        with open(self.notion_file, "w") as fh:
            json.dump(data, fh)

    def test_success(self):
        self.write_notion({"token": "secret_TOKEN_123", "page_id": "01234567-89ab-cdef-0123-456789ABCDEF"})
        code, _ = self.run_digest()
        self.assertEqual(code, 0)
        self.assertEqual(self.notion.hosts, ["api.notion.com"])
        [(method, path, headers, body)] = self.notion.requests
        self.assertEqual((method, path), ("PATCH", "/v1/blocks/0123456789abcdef0123456789abcdef/children"))
        h = {k.lower(): v for k, v in headers.items()}
        self.assertEqual(h["host"], "api.notion.com")
        self.assertEqual(h["authorization"], "Bearer secret_TOKEN_123")
        self.assertEqual(h["notion-version"], "2022-06-28")
        kinds = [b["type"] for b in body["children"]]
        self.assertEqual(kinds[0], "heading_2")
        self.assertIn("table", kinds)
        self.assertIn("quote", kinds)
        self.assertEqual(body["children"][0]["heading_2"]["rich_text"][0]["text"]["content"], "2030-03-20")
        table = next(b for b in body["children"] if b["type"] == "table")
        self.assertEqual(table["table"]["table_width"], len(table["table"]["children"][0]["table_row"]["cells"]))
        self.assertNotIn("secret_TOKEN_123", self.logs)
        self.assertIn("Notion: appended", self.logs)

    def test_failure_does_not_fail_the_run(self):
        self.write_notion({"token": "secret_TOKEN_123", "page_id": self.PAGE})
        self.notion.status = 401
        code, _ = self.run_digest()
        self.assertEqual(code, 0)
        self.assertIn("## 2030-03-20", self.read_log())
        self.assertIn("Notion answered HTTP 401", self.logs)
        self.assertNotIn("secret_TOKEN_123", self.logs)

    def test_unreachable_does_not_fail_the_run(self):
        self.write_notion({"token": "secret_TOKEN_123", "page_id": self.PAGE})
        self.notion.__exit__(None, None, None)
        code, _ = self.run_digest()
        self.assertEqual(code, 0)
        self.assertIn("Notion: not updated", self.logs)
        self.assertNotIn("secret_TOKEN_123", self.logs)

    def test_absent_token_file_means_no_call(self):
        code, _ = self.run_digest()
        self.assertEqual(code, 0)
        self.assertEqual(self.notion.requests, [])
        self.assertEqual(self.notion.hosts, [])
        self.assertIn("Notion: off", self.logs)

