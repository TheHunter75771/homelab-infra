class ConfigTest(unittest.TestCase):
    def test_validation(self):
        base = {"moneyhub_url": "http://127.0.0.1:8710", "broker_url": "http://127.0.0.1:11434"}
        cfg = config.validate(base)
        self.assertEqual(cfg["library_root"], "/srv/ai-library")
        self.assertEqual(cfg["timezone"], "America/New_York")
        self.assertIs(cfg["ai_summary"], True)
        for bad in ({"moneyhub_url": "http://u:p@h:1/x"}, {"broker_url": "http://127.0.0.1:8710"},
                    {"broker_url": "ftp://x"}, {"timezone": "Mars/Base"}, {"bills_window_days": 29},
                    {"broker_timeout_s": True}, {"library_root": "rel"}, {"model": "a b"}, {"ai_summary": "yes"}):
            with self.assertRaises(config.ConfigError, msg=bad):
                config.validate(dict(base, **bad))
        self.assertIsNone(config.validate({"moneyhub_url": "http://h:1", "ai_summary": False})["broker_url"])

    def test_broker_is_never_money_hub(self):
        same = [
            ("http://127.0.0.1:8710", "http://localhost:8710"),
            ("http://127.0.0.1:8710", "http://LOCALHOST.:8710/"),
            ("http://127.0.0.1:8710", "http://127.0.0.1:08710"),
            ("http://127.0.0.1:8710", "http://[::ffff:127.0.0.1]:8710"),
            ("http://127.0.0.1:8710", "http://127.0.0.2:8710"),          # all loopback is this host
            ("http://127.0.0.1:8710", "http://[::1]:8710"),
            ("http://100.64.0.5:80", "http://100.64.0.5"),               # default port
            ("https://100.64.0.5", "https://100.64.0.5:443"),
            ("http://100.64.0.5:8710", "http://[::ffff:100.64.0.5]:8710"),
            ("http://[fd7a:115c::5]:8710", "http://[FD7A:115C:0:0::5]:8710"),
            ("http://hub.example:8710", "http://HUB.example.:8710"),
        ]
        for hub, broker in same:
            with self.assertRaises(config.ConfigError, msg=(hub, broker)):
                config.validate({"moneyhub_url": hub, "broker_url": broker})
        different = [
            ("http://127.0.0.1:8710", "http://127.0.0.1:11434"),
            ("http://100.64.0.5:80", "http://100.64.0.5:8080"),
            ("http://100.64.0.5", "https://100.64.0.5"),                 # 80 vs 443
            ("http://100.64.0.5:8710", "http://100.64.0.6:8710"),
        ]
        for hub, broker in different:
            config.validate({"moneyhub_url": hub, "broker_url": broker})
        # the broker module refuses on its own too (literal rule, no DNS)
        for hub, broker in same:
            with self.assertRaisesRegex(broker_mod.BrokerError, "is the Money Hub URL", msg=(hub, broker)):
                broker_mod.summarise(broker, hub, "m", "facts", 1)
        with self.assertRaises(config.ConfigError):
            config.validate({"broker_url": "http://h:1"})


