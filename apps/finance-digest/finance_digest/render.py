"""One day's entry as Markdown: plain paragraphs and plain tables only (no links, no images).

Every dynamic string reached here through ``text.clean`` (Money Hub text, the AI summary) or was
formatted by this package, so it holds no ``<``, ``|``, ``[``, ``(`` or ``!``: no HTML, no forged
table cell, no link or image, and no forged day marker in the log file.
"""
from __future__ import annotations

import datetime as dt

from .text import clean

GENERATED_BY = "generated by finance-digest"
AI_LABEL = "AI summary (local model; may be imprecise; the table is authoritative)"


_ACTIVE = ("<", ">", "[", "]", "|", "`", "://", "www.", "\n", "\r")


def _cell(value: object, limit: int = 2000) -> str:
    """Belt and braces: text with any markup-active character goes through clean() again.

    Money Hub text was already cleaned when the facts were computed, and this package's own text
    uses none of these, so normally nothing changes (and parentheses stay readable).
    """
    s = str(value)
    if any(a in s.lower() for a in _ACTIVE) or len(s) > limit:
        s = clean(s, limit)
    return s or " "


def facts_markdown(blocks: list[tuple]) -> str:
    """The facts alone (also the text the model is given)."""
    parts: list[str] = []
    for block in blocks:
        if block[0] == "para":
            parts.append(_cell(block[1]))
        else:
            _, caption, header, rows = block
            lines = [_cell(caption), "| " + " | ".join(_cell(h) for h in header) + " |",
                     "|" + "---|" * len(header)]
            lines.extend("| " + " | ".join(_cell(c) for c in row) + " |" for row in rows)
            parts.append("\n".join(lines))
    return "\n\n".join(parts)


def summary_lines(summary: str | None, note: str) -> str:
    if summary:
        return f"> {AI_LABEL}: {clean(summary, 2000)}"
    return note


def entry_markdown(day: dt.date, blocks: list[tuple], summary: str | None, note: str) -> str:
    return (
        f"## {day.isoformat()}\n\n"
        + facts_markdown(blocks)
        + "\n\n"
        + summary_lines(summary, note)
        + f"\n\n{GENERATED_BY}\n"
    )
