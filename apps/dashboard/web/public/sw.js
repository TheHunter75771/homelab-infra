const SHELL_PREFIX = 'homelab-shell-';
const SHELL_CACHE = `${SHELL_PREFIX}${VERSION}`;
const DATA_CACHE = 'homelab-data-v1';
const META_CACHE = 'push-core-meta';
const SNAPSHOT_KEY = '/__snapshot';
const DEFAULT_TITLE = 'Homelab alert';
const SHELL_PATHS = new Set(SHELL);

self.addEventListener('install', (event) => {
  // Bypass the HTTP cache so the precache is exactly this deploy's files.
  event.waitUntil(caches.open(SHELL_CACHE).then((cache) => cache.addAll(SHELL.map((p) => new Request(p, { cache: 'reload', credentials: 'same-origin' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith(SHELL_PREFIX) && n !== SHELL_CACHE).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

// The page asks a waiting version to take over once it's safe to reload (boot.js).
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'skip-waiting') self.skipWaiting();
});

async function fromShell(request, key) {
  const cache = await caches.open(SHELL_CACHE);
  const hit = await cache.match(key);
  if (hit) return hit;
  // Not precached (evicted, or the install is still running): the network, keeping only a good copy.
  try {
    const res = await fetch(request);
    if (res.ok) await cache.put(key, res.clone());
    return res;
  } catch {
    return Response.error();
  }
}

async function saveSnapshot(summary) {
  const cache = await caches.open(DATA_CACHE);
  await cache.put(
    SNAPSHOT_KEY,
    new Response(JSON.stringify({ savedAt: Date.now(), summary }), { headers: { 'Content-Type': 'application/json' } }),
  );
}

async function summaryFetch(request) {
  const res = await fetch(request); // a network error reaches the page, which then reads the snapshot
  if (res.status === 200) {
    res
      .clone()
      .json()
      .then((summary) => (summary && typeof summary === 'object' && !Array.isArray(summary) ? saveSnapshot(summary) : undefined))
      .catch(() => {});
  }
  return res; // a 5xx goes to the page as it is: the app treats it as unreachable and keeps the snapshot
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/api/summary') {
    event.respondWith(summaryFetch(request));
    return;
  }
  if (request.mode === 'navigate') {
    if (url.pathname === '/' || url.pathname === '/index.html') event.respondWith(fromShell(request, '/'));
    return;
  }
  if (SHELL_PATHS.has(url.pathname) && url.pathname !== '/') event.respondWith(fromShell(request, url.pathname));
});

// --- push --------------------------------------------------------------------------------------

function parsePayload(data) {
  if (!data) return {};
  try {
    const value = data.json();
    return value && typeof value === 'object' ? value : {};
  } catch {
    return { body: data.text() };
  }
}

// Only same-origin targets; anything else opens the app root.
function safeUrl(url) {
  try {
    const target = new URL(typeof url === 'string' && url ? url : '/', self.location.origin);
    return target.origin === self.location.origin ? target.href : new URL('/', self.location.origin).href;
  } catch {
    return new URL('/', self.location.origin).href;
  }
}

self.addEventListener('push', (event) => {
  const payload = parsePayload(event.data);
  const title = typeof payload.title === 'string' && payload.title.trim() ? payload.title : DEFAULT_TITLE;
  const options = {
    body: typeof payload.body === 'string' ? payload.body : '',
    icon: '/icons/icon-192.png',
    badge: '/icons/badge-96.png',
    data: { url: safeUrl(payload.url) },
  };
  if (typeof payload.tag === 'string' && payload.tag) {
    options.tag = payload.tag; // replaces an earlier notification with the same tag
    options.renotify = true; // ...and still alerts
  }
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = safeUrl(event.notification.data && event.notification.data.url);
  const target = new URL(url);
  event.waitUntil(
    (async () => {
      // Reuse only a window that is already exactly on the target path, and never navigate another tab:
      // it may hold unsaved state.
      const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      for (const client of windows) {
        const current = new URL(client.url);
        if (current.origin === target.origin && current.pathname === target.pathname) {
          // Dashboard routes live in the hash; ask the page to switch screens, don't navigate it.
          if (target.hash.startsWith('#/') && typeof client.postMessage === 'function') {
            client.postMessage({ type: 'open-route', hash: target.hash });
          }
          return client.focus();
        }
      }
      return self.clients.openWindow(url);
    })(),
  );
});

function b64urlToBytes(value) {
  const b64 = value.replace(/-/g, '+').replace(/_/g, '/').padEnd(Math.ceil(value.length / 4) * 4, '=');
  return Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
}

async function post(path, body) {
  return fetch(path, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-Homelab': '1' },
    body: JSON.stringify(body),
    credentials: 'same-origin',
  });
}

// The browser rotated or expired the subscription: register the new one so alerts keep arriving.
self.addEventListener('pushsubscriptionchange', (event) => {
  event.waitUntil(
    (async () => {
      let sub = event.newSubscription;
      if (!sub) {
        const res = await fetch('/api/vapid-public-key', { cache: 'no-store' });
        if (!res.ok) return;
        const { publicKey } = await res.json();
        sub = await self.registration.pushManager.subscribe({
          userVisibleOnly: true,
          applicationServerKey: b64urlToBytes(publicKey),
        });
      }
      let label = 'device';
      try {
        const cached = await (await caches.open(META_CACHE)).match('/__label');
        if (cached) label = (await cached.text()) || label;
      } catch {
        // keep the default
      }
      await post('/api/subscribe', { subscription: sub.toJSON(), label });
      if (event.oldSubscription && event.oldSubscription.endpoint !== sub.endpoint) {
        await post('/api/unsubscribe', { endpoint: event.oldSubscription.endpoint });
      }
    })().catch(() => {}),
  );
});
