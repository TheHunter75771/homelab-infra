// Dashboard v2 service worker (scope /).
//
// Shell: versioned and atomic.
// - `install` precaches the whole shell into `homelab-shell-<VERSION>` with cache.addAll. If any file
//   fails, the install fails and the old worker keeps serving.
// - Shell requests are answered from the active version's cache only. A page is therefore always served
//   from one version, and a 502/503/504 from `tailscale serve` (dashboard down, box up) can never replace
//   it. The network is used only for a file that isn't cached, and then only a 2xx is kept.
// - A new version waits; the page asks it to take over only once it has fully loaded and is idle, then
//   reloads (boot.js). `activate` drops the old version's cache.
//
// /api/summary: passes through. A 200 is saved with its time for the offline screen; a 5xx never replaces
// that copy.
//
// Push (CONTRACTS §5 payload {title, body, tag, url}) and notification clicks, as push-core did.
// The worker answers only the exact shell paths and /api/summary. Everything else goes to the network
// untouched.

// <shell> Generated by scripts/stamp-sw.mjs from the files in public/. Run `npm run stamp` after changing any.
