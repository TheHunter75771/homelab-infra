#!/usr/bin/env node
// Writes the shell list and its content hash into public/sw.js (between the <shell> markers). The version
// changes whenever any shell file changes, so browsers install a new worker, which precaches the new shell
// in one piece. `--check` exits 1 when sw.js is out of date (the tests run it). `--dir <path>` stamps
// another copy of public/ (used by the browser test that simulates a deploy).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, base = dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p, base));
    else out.push(path.relative(base, p).split(path.sep).join('/'));
  }
  return out;
}

// Everything the page loads: all of public/ except the worker itself and the license texts.
export function shellFiles(dir) {
  return walk(dir)
    .filter((f) => f !== 'sw.js' && !/(^|\/)LICENSE[^/]*$/.test(f) && !f.split('/').some((p) => p.startsWith('.')))
    .sort();
}

export function shellBlock(dir) {
  const files = shellFiles(dir);
  const hash = crypto.createHash('sha256');
  for (const f of files) {
    hash.update(f);
    hash.update('\0');
    hash.update(fs.readFileSync(path.join(dir, f)));
    hash.update('\0');
  }
  const version = hash.digest('hex').slice(0, 16);
  const urls = files.map((f) => (f === 'index.html' ? '/' : `/${f}`));
  return [
    '// <shell> Generated by scripts/stamp-sw.mjs from the files in public/. Run `npm run stamp` after changing any.',
    `const VERSION = '${version}';`,
    'const SHELL = [',
    ...urls.map((u) => `  '${u}',`),
    '];',
    '// </shell>',
  ].join('\n');
}

export function stamp(dir, { check = false } = {}) {
  const swPath = path.join(dir, 'sw.js');
  const sw = fs.readFileSync(swPath, 'utf8');
  const re = /\/\/ <shell>[\s\S]*?\/\/ <\/shell>/;
  if (!re.test(sw)) throw new Error('sw.js has no <shell> block');
  const next = sw.replace(re, shellBlock(dir));
  if (next === sw) return { changed: false };
  if (check) return { changed: true };
  fs.writeFileSync(swPath, next);
  return { changed: true };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const i = process.argv.indexOf('--dir');
  const dir = i > -1 ? path.resolve(process.argv[i + 1]) : path.join(ROOT, 'public');
  const check = process.argv.includes('--check');
  const { changed } = stamp(dir, { check });
  if (check && changed) {
    console.error('public/sw.js is out of date: run npm run stamp');
    process.exit(1);
  }
  console.log(changed ? 'stamped sw.js' : 'sw.js is up to date');
}
